// ─── Color Helpers ───────────────────────────────────────────────────────────

const NO_COLOR = !!(process.env['NO_COLOR'] || process.env['TERM'] === 'dumb');

const colors = {
  reset: NO_COLOR ? '' : '\x1b[0m',
  bold: NO_COLOR ? '' : '\x1b[1m',
  dim: NO_COLOR ? '' : '\x1b[2m',
  red: NO_COLOR ? '' : '\x1b[31m',
  green: NO_COLOR ? '' : '\x1b[32m',
  yellow: NO_COLOR ? '' : '\x1b[33m',
  blue: NO_COLOR ? '' : '\x1b[34m',
  cyan: NO_COLOR ? '' : '\x1b[36m',
  magenta: NO_COLOR ? '' : '\x1b[35m',
};

function colorize(color: keyof typeof colors, text: string): string {
  return `${colors[color]}${text}${colors.reset}`;
}

// ─── Progress Indicator ──────────────────────────────────────────────────────

class Spinner {
  private frames = ['⠋', '⠙', '⠹', '⠸', '⠼', '⠴', '⠦', '⠧', '⠇', '⠏'];
  private interval: ReturnType<typeof setInterval> | null = null;
  private frameIndex = 0;

  start(message: string): void {
    if (NO_COLOR || !process.stdout.isTTY) {
      process.stdout.write(`${message}...\n`);
      return;
    }
    this.frameIndex = 0;
    this.interval = setInterval(() => {
      const frame = this.frames[this.frameIndex % this.frames.length];
      process.stdout.write(`\r${colorize('cyan', frame)} ${message}`);
      this.frameIndex++;
    }, 80);
  }

  stop(message?: string): void {
    if (this.interval) {
      clearInterval(this.interval);
      this.interval = null;
      process.stdout.write('\r\x1b[K');
    }
    if (message) {
      process.stdout.write(`${message}\n`);
    }
  }
}

// ─── CLI Config ──────────────────────────────────────────────────────────────

interface CliFlags {
  json: boolean;
  verbose: boolean;
  file?: string;
  help: boolean;
}

function parseCliArgs(): { command: string; args: string[]; flags: CliFlags } {
  const { values, positionals } = parseArgs({
    allowPositionals: true,
    options: {
      json: { type: 'boolean', default: false },
      verbose: { type: 'boolean', default: false },
      file: { type: 'string', short: 'f' },
      help: { type: 'boolean', default: false, short: 'h' },
    },
  });

  const command = positionals[0] ?? '';
  const args = positionals.slice(1);

  return {
    command,
    args,
    flags: {
      json: values.json ?? false,
      verbose: values.verbose ?? false,
      file: values.file,
      help: values.help ?? false,
    },
  };
}

