#!/usr/bin/env node
/**
 * Buggy CLI
 *
 * Command-line interface for running the proof-carrying debugger
 * against any target project.
 *
 * Usage:
 *   buggy init
 *   buggy analyze <file>
 *   buggy investigate <function> --file <path>
 *   buggy status <id>
 *   buggy halt <id>
 */

